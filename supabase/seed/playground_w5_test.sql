begin;

do $$
declare
  v_changed int := 0;
  v_key text; v_kind text; v_ms int; v_inst text[]; v_grid jsonb;
  v_game text; v_skill text; v_mode text; v_steps jsonb; v_params jsonb; v_tpl bigint;
  v_item jsonb; v_asset bigint; v_seq text[]; v_skills text[];
begin
  -- 1. TEST sounds (generated by the app).
  for v_key, v_kind, v_ms, v_inst, v_grid in values
    ('synth:instrument:mridanga', 'instrument', 4000, array['mridanga'], null::jsonb),
    ('synth:instrument:kartal', 'instrument', 4000, array['kartal'], null),
    ('synth:instrument:harmonium', 'instrument', 4000, array['harmonium'], null),
    ('synth:instrument:kartal+mridanga', 'instrument', 4000, array['kartal', 'mridanga'], null),
    ('synth:instrument:harmonium+kartal', 'instrument', 4000, array['harmonium', 'kartal'], null),
    ('synth:instrument:harmonium+mridanga', 'instrument', 4000, array['harmonium', 'mridanga'], null),
    ('synth:tone:0', 'tone', 2000, '{}', null),
    ('synth:tone:2', 'tone', 2000, '{}', null),
    ('synth:tone:4', 'tone', 2000, '{}', null),
    ('synth:tone:7', 'tone', 2000, '{}', null),
    ('synth:tone:0,2', 'tone', 2400, '{}', null),
    ('synth:tone:0,4', 'tone', 2400, '{}', null),
    ('synth:tone:0,2,4,2,0', 'tone', 6000, '{}', null),
    ('synth:tone:0,2,4', 'voice', 3000, '{}', null),
    ('synth:tone:0,2,4,2', 'voice', 4000, '{}', null),
    ('synth:kirtan:slow', 'kirtan', 33000, '{}',
     '{"sam_ms":[0,8000,16000,24000],"beats":8,"bpm":60,"entries_ms":[16000],"tempo_changes":[]}'),
    ('synth:kirtan:medium', 'kirtan', 25000, '{}',
     '{"sam_ms":[0,6000,12000,18000],"beats":8,"bpm":80,"entries_ms":[12000],"tempo_changes":[]}')
  loop
    if not exists (select 1 from play_assets where placeholder and bundled_key = v_key and status = 'approved') then
      insert into play_assets (kind, bundled_key, duration_ms, beat_grid, instruments, licence, performer, status, placeholder, approved_at)
      values (v_kind, v_key, v_ms, v_grid, v_inst, 'own', 'TEST (generated by the app)', 'approved', true, now());
      v_changed := v_changed + 1;
    end if;
  end loop;

  -- 2. One template per game (kept when there).
  for v_game, v_skill, v_mode, v_steps, v_params in values
    ('sound_explorer', 'listen.instrument', 'choose', '[{"step":1,"choices":2},{"step":2,"choices":3}]'::jsonb, '{"roundLen":5}'::jsonb),
    ('voice_companion', 'vocal.pitch', 'self_check', '[{"step":1},{"step":2},{"step":3}]', '{"roundLen":4}'),
    ('vocal_studio', 'vocal.pitch', 'self_check', '[{"step":1},{"step":2}]', '{"roundLen":5}'),
    ('kirtan_companion', 'kirtan.entry', 'tap', '[{"step":1},{"step":2},{"step":3}]', '{"roundLen":4}'),
    ('kirtan_sync', 'kirtan.keep', 'tap', '[{"step":1},{"step":2},{"step":3}]', '{"roundLen":4}')
  loop
    if not exists (select 1 from play_templates where placeholder and game = v_game) then
      insert into play_templates (game, skill, response_mode, level_min, level_max, steps, params, status, placeholder, approved_at)
      values (v_game, v_skill, v_mode, 1, 3, v_steps, v_params, 'approved', true, now());
      v_changed := v_changed + 1;
    end if;
  end loop;

  -- 3. Exercises: {game, sound key or null, sequence or null, skills, answer}; each added once.
  for v_item in select value from jsonb_array_elements('[
      {"g":"sound_explorer","k":"synth:instrument:mridanga","s":["listen.instrument"],"a":{"instruments":["mridanga"]}},
      {"g":"sound_explorer","k":"synth:instrument:kartal","s":["listen.instrument"],"a":{"instruments":["kartal"]}},
      {"g":"sound_explorer","k":"synth:instrument:harmonium","s":["listen.instrument"],"a":{"instruments":["harmonium"]}},
      {"g":"sound_explorer","k":"synth:instrument:kartal+mridanga","s":["listen.instrument"],"a":{"instruments":["kartal","mridanga"]}},
      {"g":"sound_explorer","k":"synth:instrument:harmonium+kartal","s":["listen.instrument"],"a":{"instruments":["harmonium","kartal"]}},
      {"g":"sound_explorer","k":"synth:instrument:harmonium+mridanga","s":["listen.instrument"],"a":{"instruments":["harmonium","mridanga"]}},
      {"g":"voice_companion","k":"synth:tone:0","s":["vocal.pitch"]},
      {"g":"voice_companion","k":"synth:tone:2","s":["vocal.pitch"]},
      {"g":"voice_companion","k":"synth:tone:4","s":["vocal.pitch"]},
      {"g":"voice_companion","k":"synth:tone:7","s":["vocal.pitch"]},
      {"g":"voice_companion","k":"synth:tone:0,2","s":["vocal.pitch"]},
      {"g":"voice_companion","k":"synth:tone:0,4","s":["vocal.pitch"]},
      {"g":"voice_companion","k":"synth:tone:0,2,4,2,0","s":["vocal.pitch"]},
      {"g":"vocal_studio","k":"synth:tone:0,2,4","s":["vocal.pitch"]},
      {"g":"vocal_studio","k":"synth:tone:0","s":["vocal.steady"]},
      {"g":"vocal_studio","q":["te"],"s":["vocal.bol_recite"]},
      {"g":"vocal_studio","q":["khe"],"s":["vocal.bol_recite"]},
      {"g":"vocal_studio","q":["te","re","khe","ta"],"s":["vocal.bol_recite"]},
      {"g":"vocal_studio","k":"synth:tone:0,2,4,2","s":["vocal.call_response"]},
      {"g":"kirtan_companion","k":"synth:kirtan:slow","s":["kirtan.entry"]},
      {"g":"kirtan_companion","k":"synth:kirtan:medium","s":["kirtan.entry"]},
      {"g":"kirtan_sync","k":"synth:kirtan:slow","s":["kirtan.keep"]},
      {"g":"kirtan_sync","k":"synth:kirtan:medium","s":["kirtan.keep"]}
    ]'::jsonb)
  loop
    v_game := v_item ->> 'g';
    select id into v_tpl from play_templates where placeholder and game = v_game order by id limit 1;
    v_asset := null;
    if v_item ? 'k' then
      select id into v_asset from play_assets where placeholder and bundled_key = v_item ->> 'k' and status = 'approved' order by id limit 1;
    end if;
    v_seq := case when v_item ? 'q' then array(select jsonb_array_elements_text(v_item -> 'q')) end;
    v_skills := array(select jsonb_array_elements_text(v_item -> 's'));
    if not exists (select 1 from play_exercises where placeholder and game = v_game and status = 'approved'
                     and skills = v_skills and coalesce(prompt_assets, '{}') = case when v_asset is null then '{}'::bigint[] else array[v_asset] end
                     and sequence is not distinct from v_seq) then
      insert into play_exercises (game, template_id, level_id, skills, sequence, answer, prompt_assets, bpm_min, bpm_max, status, placeholder, approved_at)
      values (v_game, v_tpl, 1, v_skills, v_seq, coalesce(v_item -> 'a', '{}'),
              case when v_asset is null then '{}'::bigint[] else array[v_asset] end,
              case when v_seq is not null then 60 end, case when v_seq is not null then 72 end, 'approved', true, now());
      v_changed := v_changed + 1;
    end if;
  end loop;

  if v_changed > 0 then
    perform publish_playground('TEST placeholders: voice, kirtan, instruments (supabase/seed/playground_w5_test.sql)');
  end if;
end $$;

